namespace Workes.ConsoleSystem.Presentation;

/// <summary>
/// Standard formatting attribute identifiers used by the built-in formatting presets.
/// </summary>
public static class ConsoleStandardFormatAttributes
{
    /// <summary>
    /// Foreground text color.
    /// </summary>
    public const string ForegroundColor = "foreground-color";

    /// <summary>
    /// Bold text flag.
    /// </summary>
    public const string Bold = "bold";

    /// <summary>
    /// Italic text flag.
    /// </summary>
    public const string Italic = "italic";

    /// <summary>
    /// Underline text flag.
    /// </summary>
    public const string Underline = "underline";
}
